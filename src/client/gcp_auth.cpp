void AccessTokens::resolve() {
    resolved_ = true;

    // A JSON key, named explicitly or found where gcloud leaves it. Both files
    // have the same shape; `type` says which grant to run.
    const std::string named = env_str("GOOGLE_APPLICATION_CREDENTIALS");
    const std::string path  = named.empty() ? well_known_adc_path() : named;

    if (path.empty()) {
        platform::log_warn("gcp auth: nothing to read -- GOOGLE_APPLICATION_CREDENTIALS is "
                           "not set in this process's environment, and the gcloud config "
                           "directory could not be located either (no CLOUDSDK_CONFIG, no "
                           "HOME, no passwd entry). Asking the metadata server instead.");
    } else {
        const std::string raw = read_file(path);
        if (raw.empty()) {
            // Logged either way, and this is the point: a deployment that meant
            // to authenticate from a credential file and simply never got the
            // variable into the server's environment is otherwise
            // indistinguishable, in this log, from one correctly running on GCP
            // with nothing configured. The difference is the whole diagnosis, and
            // leaving the reader to guess at it is what this line exists for.
            if (!named.empty()) {
                platform::log_warn("gcp auth: GOOGLE_APPLICATION_CREDENTIALS='%s' cannot be "
                                   "read (missing, or not readable by this process's user). "
                                   "Asking the metadata server instead.", path.c_str());
            } else {
                platform::log_info("gcp auth: GOOGLE_APPLICATION_CREDENTIALS is not set in "
                                   "this process's environment and '%s' does not exist, so "
                                   "credentials will be asked of the metadata server. That "
                                   "is correct ON GCP and cannot work anywhere else -- off "
                                   "GCP, point that variable at a service-account key or at "
                                   "the external_account file a workload identity federation "
                                   "setup produces. It is read from the ENVIRONMENT only, "
                                   "the way google.auth reads it; a value in config.yml has "
                                   "no effect.", path.c_str());
            }
        } else {
            rapidjson::Document d;
            if (d.Parse(raw.c_str()).HasParseError() || !d.IsObject()) {
                platform::log_warn("gcp auth: credential file '%s' is not JSON", path.c_str());
            } else {
                const std::string type = member_str(d, "type");
                if (type == "service_account") {
                    sa_client_email_ = member_str(d, "client_email");
                    sa_private_key_  = member_str(d, "private_key");
                    sa_token_uri_    = member_str(d, "token_uri");
                    if (sa_token_uri_.empty()) sa_token_uri_ = kTokenUri;
                    if (!sa_client_email_.empty() && !sa_private_key_.empty()) {
                        source_ = CredentialSource::ServiceAccount;
                        platform::log_info("gcp auth: service-account credentials for %s (%s)",
                                           sa_client_email_.c_str(), path.c_str());
                        return;
                    }
                    platform::log_warn("gcp auth: service-account file '%s' lacks "
                                       "client_email / private_key", path.c_str());
                } else if (type == "authorized_user") {
                    au_client_id_     = member_str(d, "client_id");
                    au_client_secret_ = member_str(d, "client_secret");
                    au_refresh_token_ = member_str(d, "refresh_token");
                    if (!au_client_id_.empty() && !au_refresh_token_.empty()) {
                        source_ = CredentialSource::AuthorizedUser;
                        platform::log_info("gcp auth: authorized-user credentials (%s)",
                                           path.c_str());
                        return;
                    }
                    platform::log_warn("gcp auth: authorized-user file '%s' lacks "
                                       "client_id / refresh_token", path.c_str());
                } else if (type == "external_account") {
                    // Workload identity federation: no key here, only what is
                    // needed to prove this workload's own identity elsewhere.
                    ea_audience_           = member_str(d, "audience");
                    ea_subject_token_type_ = member_str(d, "subject_token_type");
                    ea_token_url_          = member_str(d, "token_url");
                    if (ea_token_url_.empty()) ea_token_url_ = kStsTokenUrl;
                    ea_impersonation_url_  = member_str(d, "service_account_impersonation_url");
                    ea_cs_file_            = member_str_in(d, "credential_source", "file");
                    ea_cs_url_             = member_str_in(d, "credential_source", "url");
                    ea_cs_environment_id_  = member_str_in(d, "credential_source", "environment_id");
                    ea_cs_region_url_      = member_str_in(d, "credential_source", "region_url");
                    ea_cs_security_creds_url_ = member_str_in(d, "credential_source", "url");
                    ea_cs_imdsv2_url_      = member_str_in(d, "credential_source",
                                                           "imdsv2_session_token_url");
                    ea_cs_regional_verification_url_ =
                        member_str_in(d, "credential_source", "regional_cred_verification_url");
                    // credential_source.format: {"type":"json","subject_token_field_name":...}
                    rapidjson::Value::ConstMemberIterator cs = d.FindMember("credential_source");
                    if (cs != d.MemberEnd() && cs->value.IsObject()) {
                        ea_cs_format_ = member_str_in(cs->value, "format", "type");
                        ea_cs_field_  = member_str_in(cs->value, "format",
                                                      "subject_token_field_name");
                        // credential_source.headers: sent with the GET when the
                        // token comes from a url (identity_pool.py) -- for an
                        // endpoint that wants a credential of its own before it
                        // will hand one out.
                        rapidjson::Value::ConstMemberIterator h = cs->value.FindMember("headers");
                        if (h != cs->value.MemberEnd() && h->value.IsObject()) {
                            for (rapidjson::Value::ConstMemberIterator m = h->value.MemberBegin();
                                 m != h->value.MemberEnd(); ++m) {
                                if (!m->value.IsString()) continue;
                                ea_cs_headers_.push_back(std::string(m->name.GetString()) + ": " +
                                                         m->value.GetString());
                            }
                        }
                    }
                    if (!ea_audience_.empty() && !ea_token_url_.empty()) {
                        source_ = CredentialSource::ExternalAccount;
                        platform::log_info("gcp auth: workload identity federation for %s "
                                           "(source: %s%s)",
                                           ea_audience_.c_str(),
                                           !ea_cs_file_.empty() ? "token file"
                                             : !ea_cs_environment_id_.empty() ? ea_cs_environment_id_.c_str()
                                             : !ea_cs_url_.empty() ? "token url" : "unknown",
                                           ea_impersonation_url_.empty() ? ""
                                                                         : ", impersonated");
                        return;
                    }
                    platform::log_warn("gcp auth: external-account file '%s' names no "
                                       "audience", path.c_str());
                } else {
                    // An absent `type` used to fall through in total silence,
                    // which is the same dead end as the file not being there at
                    // all but says nothing about which one happened.
                    const std::string what = type.empty()
                        ? std::string("no \"type\" field")
                        : ("an unsupported type '" + type + "'");
                    platform::log_warn("gcp auth: credential file '%s' has %s -- expected "
                                       "service_account, authorized_user or external_account",
                                       path.c_str(), what.c_str());
                }
            }
        }
    }

    // Nothing on disk: assume we are running on GCP and let the metadata server
    // answer. Whether it is actually there is decided by the first mint, not
    // here -- probing at resolve time would cost a round trip even for a process
    // that never calls Vertex.
    source_ = CredentialSource::Metadata;
}

