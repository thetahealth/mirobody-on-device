// "2026-08-06T12:34:56Z" -> unix seconds, or 0 when it will not parse. The
// impersonation endpoint reports expiry this way rather than as a lifetime.
std::int64_t parse_rfc3339(const std::string& s) {
    int y = 0, mo = 0, d = 0, h = 0, mi = 0, sec = 0;
    if (std::sscanf(s.c_str(), "%d-%d-%dT%d:%d:%d", &y, &mo, &d, &h, &mi, &sec) != 6) return 0;
    std::tm tm = std::tm();
    tm.tm_year = y - 1900; tm.tm_mon = mo - 1; tm.tm_mday = d;
    tm.tm_hour = h; tm.tm_min = mi; tm.tm_sec = sec;
#ifdef _WIN32
    const std::time_t t = _mkgmtime(&tm);
#else
    const std::time_t t = timegm(&tm);
#endif
    return t == static_cast<std::time_t>(-1) ? 0 : static_cast<std::int64_t>(t);
}

