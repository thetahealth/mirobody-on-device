const char* source_name(CredentialSource s) {
    switch (s) {
        case CredentialSource::ServiceAccount: return "service account";
        case CredentialSource::AuthorizedUser:  return "authorized user";
        case CredentialSource::ExternalAccount: return "workload identity federation";
        case CredentialSource::Metadata:       return "metadata server";
        default:                               return "none";
    }
}

