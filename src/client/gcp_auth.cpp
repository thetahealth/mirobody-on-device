// Google's token endpoint, and the grant the RFC 7523 assertion flow names. A
// service-account key carries its own token_uri (these are the values it holds
// in practice); the authorized-user flow has no such field and uses this.
const char* const kTokenUri = "https://oauth2.googleapis.com/token";
const char* const kJwtBearerGrant = "urn:ietf:params:oauth:grant-type:jwt-bearer";

// Google's STS endpoint. An external-account file generated by gcloud names its
// own token_url; external_account.py falls back to this when the field is
// absent, so a hand-written file that omits it still works.
const char* const kStsTokenUrl = "https://sts.googleapis.com/v1/token";

// The instance metadata server. The Metadata-Flavor header is required and is
// what makes the request un-forgeable by a browser (it cannot be sent
// cross-origin), so Google treats its presence as proof the caller is local.
const char* const kMetadataPath =
    "/computeMetadata/v1/instance/service-accounts/default/token";

// The name GCE publishes, and the link-local address it resolves to.
//
// Both, because the name is the part that breaks: it is served by the metadata
// DNS the VM is configured with, which a container does not inherit -- so on a
// GCE VM the address answers while the name does not resolve, and a deployment
// that IS on GCP looks exactly like one that is not. Google's own libraries do
// the same thing, and read the same GCE_METADATA_HOST override.
const char* const kMetadataHost = "metadata.google.internal";
const char* const kMetadataAddr = "169.254.169.254";

// Mint a new token this many seconds before the current one expires, so a token
// cannot lapse mid-request.
const std::int64_t kExpirySkew = 60;

// After a failed mint, wait this long before trying again. Without it, a
// deployment with no credentials at all (the metadata host does not resolve)
// pays the connect timeout on every single turn.
const std::int64_t kRetryBackoff = 30;

// The metadata server is on the local link; a slow answer means it is not there.
const int kMetadataTimeoutMs = 2000;
const int kTokenEndpointTimeoutMs = 10000;

std::int64_t now_secs() { return static_cast<std::int64_t>(std::time(nullptr)); }

std::string env_str(const char* name) {
    const char* v = std::getenv(name);
    return v ? std::string(v) : std::string();
}

std::string read_file(const std::string& path) {
    std::ifstream in(path.c_str(), std::ios::binary);
    if (!in) return std::string();
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

// The gcloud configuration directory, resolved the way google.auth's
// _cloud_sdk.get_config_path() resolves it: CLOUDSDK_CONFIG wins outright, then
// the per-platform default.
//
// The fallbacks when HOME / APPDATA is unset are not padding. A server started
// by systemd, or by a container runtime with no user environment, frequently has
// no HOME at all -- and Python's expanduser("~") quietly reads the passwd entry
// in that case, so gcloud and the Python stack still find the file. Giving up
// here instead is how a host that DOES have an ADC file comes to look exactly
// like one that does not.
std::string gcloud_config_dir() {
    const std::string override_dir = env_str("CLOUDSDK_CONFIG");
    if (!override_dir.empty()) return override_dir;

#ifdef _WIN32
    const std::string appdata = env_str("APPDATA");
    if (!appdata.empty()) return appdata + "\\gcloud";
    const std::string drive = env_str("SystemDrive");
    return (drive.empty() ? std::string("C:") : drive) + "\\gcloud";
#else
    std::string home = env_str("HOME");
    if (home.empty()) {
        const struct passwd* pw = getpwuid(getuid());
        if (pw != nullptr && pw->pw_dir != nullptr) home = pw->pw_dir;
    }
    if (home.empty()) return std::string();
    return home + "/.config/gcloud";
#endif
}

// Where `gcloud auth application-default login` writes its credentials -- the
// path google.auth checks when GOOGLE_APPLICATION_CREDENTIALS is unset.
std::string well_known_adc_path() {
    const std::string dir = gcloud_config_dir();
    if (dir.empty()) return std::string();
#ifdef _WIN32
    return dir + "\\application_default_credentials.json";
#else
    return dir + "/application_default_credentials.json";
#endif
}

// A string member, or "" when absent / not a string.
std::string member_str(const rapidjson::Value& v, const char* key) {
    rapidjson::Value::ConstMemberIterator it = v.FindMember(key);
    if (it != v.MemberEnd() && it->value.IsString()) {
        return std::string(it->value.GetString(), it->value.GetStringLength());
    }
    return std::string();
}

// A string member of a nested object, or "" when either is absent.
std::string member_str_in(const rapidjson::Value& v, const char* obj, const char* key) {
    rapidjson::Value::ConstMemberIterator it = v.FindMember(obj);
    if (it == v.MemberEnd() || !it->value.IsObject()) return std::string();
    return member_str(it->value, key);
}

// Percent-encode a form value. The JWT assertion is base64url (nothing to
// escape), but a refresh token or client secret can carry anything.
std::string form_encode(const std::string& s) {
    static const char* kHex = "0123456789ABCDEF";
    std::string out;
    out.reserve(s.size());
    for (std::size_t i = 0; i < s.size(); ++i) {
        const unsigned char c = static_cast<unsigned char>(s[i]);
        if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ||
            c == '-' || c == '_' || c == '.' || c == '~') {
            out.push_back(static_cast<char>(c));
        } else {
            out.push_back('%');
            out.push_back(kHex[c >> 4]);
            out.push_back(kHex[c & 0x0F]);
        }
    }
    return out;
}

// RSASSA-PKCS1-v1_5 over SHA-256 -- the JWT `RS256` signature. `pem` is the
// service-account key's private half (PKCS#8, as the JSON carries it). Returns
// the raw signature bytes, or "" if the key will not load or signing fails.
std::string rs256_sign(const std::string& pem, const std::string& input) {
    BIO* bio = BIO_new_mem_buf(pem.data(), static_cast<int>(pem.size()));
    if (!bio) return std::string();
    EVP_PKEY* key = PEM_read_bio_PrivateKey(bio, nullptr, nullptr, nullptr);
    BIO_free(bio);
    if (!key) return std::string();

    std::string sig;
    EVP_MD_CTX* ctx = EVP_MD_CTX_new();
    if (ctx != nullptr &&
        EVP_DigestSignInit(ctx, nullptr, EVP_sha256(), nullptr, key) == 1 &&
        EVP_DigestSignUpdate(ctx, input.data(), input.size()) == 1) {
        std::size_t n = 0;
        if (EVP_DigestSignFinal(ctx, nullptr, &n) == 1 && n > 0) {
            sig.resize(n);
            if (EVP_DigestSignFinal(ctx, reinterpret_cast<unsigned char*>(&sig[0]), &n) == 1) {
                sig.resize(n);
            } else {
                sig.clear();
            }
        }
    }
    if (ctx != nullptr) EVP_MD_CTX_free(ctx);
    EVP_PKEY_free(key);
    return sig;
}

// A short, safe snippet of an error body for logging.
std::string snippet(const std::string& s) {
    return s.size() > 200 ? s.substr(0, 200) + "..." : s;
}

