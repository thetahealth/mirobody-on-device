bool AccessTokens::accept_token_response(const std::string& body, const char* what) {
    rapidjson::Document d;
    if (d.Parse(body.c_str()).HasParseError() || !d.IsObject()) {
        platform::log_warn("gcp auth: %s returned a non-JSON body: %s",
                           what, snippet(body).c_str());
        return false;
    }
    const std::string tok = member_str(d, "access_token");
    if (tok.empty()) {
        platform::log_warn("gcp auth: %s returned no access_token: %s",
                           what, snippet(body).c_str());
        return false;
    }
    std::int64_t ttl = 3600;
    rapidjson::Value::ConstMemberIterator it = d.FindMember("expires_in");
    if (it != d.MemberEnd() && it->value.IsInt64()) ttl = it->value.GetInt64();
    if (ttl <= kExpirySkew) ttl = kExpirySkew + 1;   // never cache a token that is already stale

    token_      = tok;
    expires_at_ = now_secs() + ttl - kExpirySkew;
    return true;
}

bool AccessTokens::refresh_service_account() {
    // RFC 7523: a JWT signed by the key, exchanged for an access token.
    const std::int64_t iat = now_secs();
    const std::int64_t exp = iat + 3600;

    const std::string header = "{\"alg\":\"RS256\",\"typ\":\"JWT\"}";
    std::ostringstream claims;
    claims << "{\"iss\":\"" << sa_client_email_ << "\","
           << "\"scope\":\"" << scope_ << "\","
           << "\"aud\":\"" << sa_token_uri_ << "\","
           << "\"iat\":" << iat << ",\"exp\":" << exp << "}";

    const std::string signing_input = storage::base64url_encode(header) + "." +
                                      storage::base64url_encode(claims.str());
    const std::string sig = rs256_sign(sa_private_key_, signing_input);
    if (sig.empty()) {
        platform::log_error("gcp auth: could not sign the assertion (bad private_key?)");
        return false;
    }
    const std::string assertion = signing_input + "." + storage::base64url_encode(sig);

    client::HttpClient http;
    client::HttpRequest req;
    req.url          = sa_token_uri_;
    req.content_type = "application/x-www-form-urlencoded";
    req.body         = "grant_type=" + form_encode(kJwtBearerGrant) +
                       "&assertion=" + form_encode(assertion);
    req.request_timeout_ms = kTokenEndpointTimeoutMs;
    const client::HttpResponse resp = http.post(req);
    if (resp.status != 200) {
        platform::log_error("gcp auth: assertion exchange failed (HTTP %ld): %s",
                            resp.status, snippet(resp.body).c_str());
        return false;
    }
    return accept_token_response(resp.body, "the token endpoint");
}

bool AccessTokens::refresh_authorized_user() {
    client::HttpClient http;
    client::HttpRequest req;
    req.url          = kTokenUri;
    req.content_type = "application/x-www-form-urlencoded";
    req.body         = "grant_type=refresh_token"
                       "&client_id="     + form_encode(au_client_id_) +
                       "&client_secret=" + form_encode(au_client_secret_) +
                       "&refresh_token=" + form_encode(au_refresh_token_);
    req.request_timeout_ms = kTokenEndpointTimeoutMs;
    const client::HttpResponse resp = http.post(req);
    if (resp.status != 200) {
        platform::log_error("gcp auth: refresh_token grant failed (HTTP %ld): %s",
                            resp.status, snippet(resp.body).c_str());
        return false;
    }
    return accept_token_response(resp.body, "the token endpoint");
}

