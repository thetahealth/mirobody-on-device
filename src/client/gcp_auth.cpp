std::string vertex_host(const std::string& location, const char* scheme) {
    const std::string s = std::string(scheme) + "://";
    if (location.empty())     return std::string();
    if (location == "global") return s + "aiplatform.googleapis.com";
    // Newer Gemini models publish the multi-regions and nothing else, so this
    // branch is not an exotic case -- it is the one a data-residency deployment
    // lands on. Both are enumerated rather than pattern-matched: "us" and "eu"
    // are the only two, and a region like "us-central1" must not be caught here.
    if (location == "us" || location == "eu")
        return s + "aiplatform." + location + ".rep.googleapis.com";
    return s + location + "-aiplatform.googleapis.com";
}

std::string vertex_model_location(
    const std::unordered_map<std::string, std::string>& per_model,
    const std::string& model,
    const std::string& fallback) {
    std::unordered_map<std::string, std::string>::const_iterator it = per_model.find(model);
    // An empty override reads as unset, the rule every other config value
    // follows (ConfigStore::get_str), so blanking one entry in the map returns
    // that model to the shared location instead of building a hostless URL.
    if (it != per_model.end() && !it->second.empty()) return it->second;
    return fallback;
}

