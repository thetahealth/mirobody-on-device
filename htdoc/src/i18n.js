var current = "en";

// Switch the active language; unknown codes are ignored (stay on the current).
function setLang(code) {
    if (STRINGS[code]) {
        current = code;
    }
};

function getLang() {
    return current;
};

// Look up a key in the active language, falling back to English then to the key
// itself. A single "%s" placeholder is replaced when `arg` is provided.
function t(key, arg) {
    var table = STRINGS[current] || STRINGS.en;
    var s = table[key];
    if (s === undefined) { s = STRINGS.en[key]; }
    if (s === undefined) { return key; }
    if (arg !== undefined) { s = s.replace("%s", arg); }
    return s;
};

